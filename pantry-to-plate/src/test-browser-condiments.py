import asyncio
from playwright.async_api import async_playwright
URL="http://127.0.0.1:8765/index.html"
res=[]
def ok(c,m): res.append(bool(c)); print(("  ✓ " if c else "  ✗ ")+m)
async def st(pg): return await pg.evaluate("JSON.parse(localStorage.getItem('p2p.v3'))")
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(); pg=await (await b.new_context(viewport={"width":1300,"height":950})).new_page()
        errs=[]; pg.on("pageerror",lambda e:errs.append(str(e)))
        await pg.goto(URL+"#kitchen"); await pg.wait_for_timeout(1200)
        await pg.click("#kitchenWelcome [data-act=clear-sample]"); await pg.click("[data-act=clear-sample-yes]"); await pg.wait_for_timeout(200)
        await pg.fill("#qaText","a jar of cinnamon, half a bottle of soy sauce, 2 cups oats, 4 bananas, 1 liter milk"); await pg.press("#qaText","Enter"); await pg.wait_for_timeout(400)
        if await pg.is_visible("#reviewForm"): await pg.click("#reviewForm button[type=submit]"); await pg.wait_for_timeout(300)
        for n in ["Salt"]: await pg.check(f"#basicsAsk label.chip:has-text('{n}') input")
        await pg.click("[data-act=basics-done]"); await pg.wait_for_timeout(300)
        c=await pg.inner_text(".item:has-text('Cinnamon')"); s=await pg.inner_text(".item:has-text('Soy sauce')")
        ok("Full jar" in c and "about 40 g" in c, f"'a jar of cinnamon' → {c.split(chr(10))[1]!r}")
        ok("Half bottle" in s, f"'half a bottle of soy sauce' → {[l for l in s.split(chr(10)) if 'bottle' in l]}")
        ok(await pg.is_visible(".item:has-text('Cinnamon') .level"), "cinnamon card shows a fill-level bar")
        print("\n  One-tap level")
        await pg.click(".item:has-text('Cinnamon') [data-act=level]"); await pg.wait_for_timeout(250)
        ok(await pg.eval_on_selector_all(".lvl","e=>e.length")==6, "'How full?' offers Full · ¾ · Half · ¼ · Almost out · Used up")
        await pg.click(".lvl:has-text('¾')"); await pg.wait_for_timeout(300)
        c=await pg.inner_text(".item:has-text('Cinnamon')"); ok("¾ jar" in c and "about 30 g" in c, f"tap ¾ → {[l for l in c.split(chr(10)) if 'jar' in l]}")
        print("\n  Cooking uses only what the recipe needs")
        await pg.evaluate("location.hash='#cook'"); await pg.wait_for_timeout(400)
        await pg.click(".pick:has-text('Banana Oatmeal')"); await pg.wait_for_timeout(300)
        await pg.click("[data-act=cooked]"); await pg.wait_for_timeout(300)
        row=await pg.inner_text(".crow:has-text('Cinnamon')")
        inp=await pg.input_value(".crow:has-text('Cinnamon') input[type=number]"); allbox=await pg.is_checked(".crow:has-text('Cinnamon') input[type=checkbox]")
        ok("¾ jar" in row and float(inp)<=3 and not allbox, f"form: you have ¾ jar; uses {inp} g (½ tsp); 'Used it all' unticked")
        await pg.click("#cookedForm button[type=submit]"); await pg.wait_for_timeout(500)
        s2=await st(pg); cin=[x for x in s2["pantry"] if x["key"]=="cinnamon"]
        g=cin[0]["qty"]*40 if cin else 0
        ok(cin and 27<=g<=29, f"after cooking: cinnamon still there, about {g:.1f} g left (30 − 1.3)")
        print("\n  Used up")
        await pg.evaluate("location.hash='#kitchen'"); await pg.wait_for_timeout(300)
        await pg.click(".item:has-text('Soy sauce') [data-act=level]"); await pg.click(".lvl.out"); await pg.wait_for_timeout(300)
        s3=await st(pg); ok(not any(x["key"]=="soy_sauce" for x in s3["pantry"]), "'Used up' removes the soy sauce")
        pg2=await (await b.new_context(viewport={"width":360,"height":800})).new_page()
        await pg2.goto(URL+"#kitchen"); await pg2.wait_for_timeout(900); await pg2.evaluate("localStorage.clear()")
        await pg2.goto(URL+"#kitchen"); await pg2.wait_for_timeout(900)
        await pg2.fill("#qaText","a jar of cumin"); await pg2.press("#qaText","Enter"); await pg2.wait_for_timeout(400)
        await pg2.click(".item:has-text('Cumin') [data-act=level]"); await pg2.wait_for_timeout(300)
        ok(await pg2.evaluate("document.documentElement.scrollWidth<=innerWidth+1"), "phone (360px): level picker fits")
        await (await pg2.query_selector("#authBox")).screenshot(path="/tmp/levels.png")
        ok(not errs, f"no script errors {errs[:2]}")
        print(f"\n{sum(res)}/{len(res)} condiment checks passed"); await b.close()
asyncio.run(main())
