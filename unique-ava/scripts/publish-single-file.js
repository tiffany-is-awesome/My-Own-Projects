// Copies the single-file build to the repo root as wearwise.html (served by GitHub Pages).
// unique-ava.html at the repo root is a tiny forwarder kept so old links keep working.
// Also writes ALL-CODE.txt: every source file in one plain-text file, so the whole app can be shared with
// another AI through one link. It is regenerated on every build, so it always matches the live site.
import { copyFileSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve, relative, join } from 'node:path';
const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');
copyFileSync(resolve(root, 'dist/index.html'), resolve(root, '../wearwise.html'));
console.log('✔ Wrote ../wearwise.html');

const walk = (dir) => readdirSync(dir).flatMap((f) => {
  const p = join(dir, f);
  return statSync(p).isDirectory() ? walk(p) : [p];
});
const order = ['src/main.jsx', 'src/App.jsx', 'src/store.jsx', 'src/config.js', 'src/auth.jsx'];
const files = [...['index.html', 'package.json', 'vite.config.js'].map((f) => resolve(root, f)),
  ...walk(resolve(root, 'src')).filter((f) => /\.(jsx?|css)$/.test(f) && !/\.test\.js$|\.fixture\.js$/.test(f))]
  .map((f) => relative(root, f))
  .sort((a, b) => {
    const ia = order.indexOf(a), ib = order.indexOf(b);
    if (ia !== -1 || ib !== -1) return (ia === -1 ? 99 : ia) - (ib === -1 ? 99 : ib);
    return a.localeCompare(b);
  });
const head = `WEARWISE — ALL SOURCE CODE (generated on every build; do not edit this file)
Live site: https://tiffany-is-awesome.github.io/My-Own-Projects/wearwise.html
Repo: https://github.com/tiffany-is-awesome/My-Own-Projects/tree/main/unique-ava
Stack: React 18 + Vite, built into one self-contained HTML file. No backend of its own:
  accounts/sync = Supabase (src/auth.jsx), AI = Google Gemini through Puter.js (src/ai/claude.js, src/ai/stylist.js),
  styling logic = rules engine (src/ai/critic.js scores outfits, src/ai/generator.js builds them), data = src/store.jsx.
Unit tests live in src/**/*.test.js (not included here). Change history: CHANGELOG.md.

FILES (${files.length}):
${files.map((f) => '  ' + f).join('\n')}
`;
const body = files.map((f) => `\n\n${'='.repeat(100)}\n FILE: unique-ava/${f}\n${'='.repeat(100)}\n\n${readFileSync(resolve(root, f), 'utf8')}`).join('');
writeFileSync(resolve(root, 'ALL-CODE.txt'), head + body);
console.log(`✔ Wrote ALL-CODE.txt (${files.length} files)`);
