import sys, json
from playwright.sync_api import sync_playwright
URL='http://localhost:8765/wearwise.html'
errs=[]; results=[]
def ok(name, cond, detail=''):
    results.append((name, bool(cond), detail)); print(('PASS' if cond else 'FAIL'), name, detail)
with sync_playwright() as p:
    b=p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
    pg=b.new_page(viewport={'width':1360,'height':900})
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.on('console', lambda m: m.type=='error' and 'ERR_TUNNEL' not in m.text and 'Failed to load resource' not in m.text and errs.append(m.text))
    pg.goto(URL); pg.wait_for_timeout(1200)
    pg.evaluate("localStorage.clear()"); pg.reload(); pg.wait_for_timeout(1200)
    ok('home shows empty-closet start', pg.get_by_text('Try the demo closet').count()>0)
    pg.goto(URL+'#/create'); pg.wait_for_timeout(500)
    pg.get_by_role('button', name='Get 3 outfits').click(); pg.wait_for_timeout(1500)
    ok('empty closet → honest missing notice, no fake outfits', pg.get_by_text('needs a few more pieces').count()>0 and pg.locator('.outfit-card').count()==0)
    # manual add
    pg.goto(URL+'#/closet'); pg.wait_for_timeout(400)
    pg.get_by_role('button', name='+ Add clothes').first.click()
    pg.get_by_role('button', name='Add without a photo').click()
    pg.locator('.item-form input.input').first.fill('Test Navy Shirt')
    pg.get_by_role('button', name='Add to closet').click(); pg.wait_for_timeout(400)
    ok('manual add works', pg.get_by_text('Test Navy Shirt').count()>0)
    # demo
    pg.goto(URL+'#/settings'); pg.wait_for_timeout(300)
    pg.get_by_role('button', name='Add the demo closet').click(); pg.wait_for_timeout(300)
    pg.goto(URL+'#/closet'); pg.wait_for_timeout(500)
    n=pg.locator('.grid .card-name').count()
    ok('demo closet loads with labels + banner', n>15 and pg.locator('.demo-banner').count()==1, f'{n} cards')
    pg.locator('select[aria-label="Color"]').select_option('black'); pg.wait_for_timeout(200)
    nb=pg.locator('.grid .card-name').count()
    ok('color filter narrows', 0<nb<n, f'{nb}')
    pg.get_by_role('button', name='Clear').click()
    # create
    pg.goto(URL+'#/create'); pg.wait_for_timeout(400)
    pg.locator('[aria-label="Occasion"]').get_by_role('button', name='Work').click()
    pg.locator('[aria-label="Weather"]').get_by_role('button', name='Rainy').click()
    pg.get_by_role('button', name='Get 3 outfits').click(); pg.wait_for_selector('.outfit-card', timeout=15000)
    cards=pg.locator('.outfit-card'); ok('3 outfits', cards.count()==3)
    txt=cards.all_inner_texts()
    ok('no suede loafers in rain', not any('Suede Penny Loafers' in t for t in txt))
    ok('each outfit has explanation', all(len(c.split('\n'))>5 for c in txt))
    ok('no demo-only family pieces leaked', not any('Mary Janes' in t or 'Dad' in t for t in txt))
    pg.screenshot(path='/tmp/wearwise-e2e/create.png', full_page=True)
    cards.nth(0).get_by_role('button', name='Improve or change').click(); pg.wait_for_timeout(300)
    alts=pg.locator('.alts .alt').count(); ok('alternatives offered', alts>0, f'{alts}')
    if alts: pg.locator('.alts .alt').first.click(); pg.wait_for_timeout(300)
    cards.nth(1).get_by_role('button', name='Save').click(); pg.wait_for_timeout(200)
    pg.get_by_role('button', name='Compare 3 side by side').click(); pg.wait_for_timeout(500)
    ok('comparison shows 3 columns', pg.locator('.compare-col').count()==3)
    ok('comparison has strengths/weaknesses/suitability', pg.get_by_text('Strengths').count()==3 and pg.get_by_text('Suitability').count()==3)
    pg.screenshot(path='/tmp/wearwise-e2e/compare.png', full_page=True)
    pg.locator('.compare-col').nth(0).get_by_role('button', name='♥ This one').click(); pg.wait_for_timeout(300)
    pg.goto(URL+'#/saved'); pg.wait_for_timeout(400)
    ok('saved outfits listed', pg.locator('.saved-card').count()>=2)
    pg.get_by_role('button', name='♥ Favorites').first.click(); pg.wait_for_timeout(200)
    fav=pg.locator('.saved-card').count(); ok('favorite filter', fav>=1, f'{fav}')
    # persist across reload
    pg.reload(); pg.wait_for_timeout(1000)
    pg.goto(URL+'#/saved'); pg.wait_for_timeout(400)
    ok('saved outfits persist in this browser after reload', pg.locator('.saved-card').count()>=2)
    # style me
    pg.goto(URL+'#/style/d-navy-dress'); pg.wait_for_timeout(600)
    sc=pg.locator('.outfit-card'); t=sc.all_inner_texts()
    ok('style me: ≥3 directions', sc.count()>=3, f'{sc.count()}')
    ok('style me: dress in every look', all('Satin Midi Slip Dress' in x or 'Navy' in x for x in t))
    pg.screenshot(path='/tmp/wearwise-e2e/styleme.png', full_page=True)
    # builder with dress → mannequin
    sc.nth(0).get_by_role('button', name='Open in builder').click(); pg.wait_for_timeout(500)
    pg.get_by_role('tab', name='Mannequin').click(); pg.wait_for_timeout(400)
    pg.screenshot(path='/tmp/wearwise-e2e/builder-dress.png')
    ok('builder shows dress slot', pg.locator('.slot .label', has_text='Dress').count()==1)
    # family
    pg.goto(URL+'#/family'); pg.wait_for_timeout(400)
    pg.get_by_role('button', name='Create family look').click(); pg.wait_for_timeout(1500)
    ok('family look: 3 members side by side', pg.locator('.family-col').count()==3)
    pg.screenshot(path='/tmp/wearwise-e2e/family.png', full_page=True)
    mia=pg.locator('.family-col').nth(2).inner_text()
    ok('kid uses only kid clothes', all(x not in mia for x in ['Chelsea','Trench','Oxford Button']), mia.replace('\n',' | ')[:120])
    pg.get_by_role('button', name='♡ Save family look').click(); pg.wait_for_timeout(300)
    ok('family look saved', pg.get_by_text('Saved family looks').count()==1)
    # profile switch separation
    pg.locator('.profile-switch select').select_option(label='Mia'); pg.wait_for_timeout(300)
    pg.goto(URL+'#/closet'); pg.wait_for_timeout(400)
    kidtxt=pg.locator('.grid').inner_text()
    ok('profile switch shows only Mia closet', 'Mary Janes' in kidtxt and 'Trench' not in kidtxt)
    pg.locator('.profile-switch select').select_option(label='Me'); pg.wait_for_timeout(200)
    # settings: remove demo, delete all
    pg.goto(URL+'#/settings'); pg.wait_for_timeout(400)
    btn=pg.get_by_role('button', name='Remove all demo items'); btn.click(); btn=pg.get_by_role('button', name='Click again to remove demo items'); btn.click(); pg.wait_for_timeout(300)
    pg.goto(URL+'#/closet'); pg.wait_for_timeout(300)
    names=pg.locator('.grid .card-name').all_inner_texts()
    ok('remove demo keeps own item only', names==['Test Navy Shirt'], str(names))
    pg.goto(URL+'#/settings'); pg.wait_for_timeout(300)
    pg.get_by_role('button', name='Delete all my Wearwise data').click(); pg.get_by_role('button', name='Click again: this cannot be undone').click(); pg.wait_for_timeout(800)
    pg.goto(URL+'#/closet'); pg.wait_for_timeout(300)
    ok('delete all empties closet', pg.get_by_text('closet is empty').count()>0)
    pg.set_viewport_size({'width':390,'height':844}); pg.goto(URL+'#/create'); pg.wait_for_timeout(400)
    pg.screenshot(path='/tmp/wearwise-e2e/mobile-create.png', full_page=True)
    ok('no page errors', not errs, '; '.join(errs[:3]))
    b.close()
print('SUMMARY', sum(r[1] for r in results), '/', len(results))
