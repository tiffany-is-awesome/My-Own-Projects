from playwright.sync_api import sync_playwright
URL='http://localhost:8765/wearwise.html'
errs=[]; res=[]
def ok(n,c,d=''): res.append(c); print('PASS' if c else 'FAIL', n, d)
with sync_playwright() as p:
    b=p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
    pg=b.new_page(viewport={'width':1360,'height':900})
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto(URL); pg.wait_for_timeout(800); pg.evaluate("localStorage.clear()"); pg.reload(); pg.wait_for_timeout(800)
    pg.goto(URL+'#/settings'); pg.wait_for_timeout(300)
    pg.get_by_role('button', name='Add the demo closet').click(); pg.wait_for_timeout(300)
    # locations
    pg.get_by_placeholder('e.g. Bedroom closet').fill('Bedroom closet'); pg.get_by_role('button', name='Add place').click()
    pg.get_by_placeholder('e.g. Bedroom closet').fill('Under-bed box'); pg.get_by_role('button', name='Add place').click(); pg.wait_for_timeout(200)
    ok('locations added in settings', pg.locator('.profile-rows input[value="Under-bed box"]').count()==1)
    pg.goto(URL+'#/closet'); pg.wait_for_timeout(400)
    pg.locator('.grid .card-name', has_text='Chunky Cable-Knit Sweater').click(); pg.wait_for_timeout(300)
    pg.locator('.loc-row select').select_option(label='Under-bed box'); pg.wait_for_timeout(300)
    pg.keyboard.press('Escape'); pg.wait_for_timeout(200)
    pg.locator('select[aria-label="Where it\'s kept"]').first.select_option(label='Under-bed box'); pg.wait_for_timeout(300)
    names=pg.locator('.grid .card-name').all_inner_texts()
    ok('filter by location', names==['Chunky Cable-Knit Sweater'], str(names))
    ok('card shows place', pg.locator('.card-place').first.inner_text().endswith('Under-bed box'))
    # new place from the item form
    pg.get_by_role('button', name='Clear').click(); pg.wait_for_timeout(200)
    pg.get_by_role('button', name='+ Add clothes').first.click(); pg.get_by_role('button', name='Add without a photo').click()
    pg.locator('.item-form input.input').first.fill('Grey Wool Socks')
    pg.locator('.item-form select[aria-label="Where it\'s kept"]').select_option('__new')
    pg.get_by_placeholder('e.g. Hallway cabinet').fill('Lola\'s house'); pg.locator('.item-form').get_by_role('button', name='Add', exact=True).click(); pg.wait_for_timeout(200)
    pg.get_by_role('button', name='Add to closet').click(); pg.wait_for_timeout(300)
    ok('new place created from item form', pg.locator('.card-place', has_text="Lola's house").count()==1)
    # history: wear + rate
    pg.goto(URL+'#/create'); pg.wait_for_timeout(300)
    pg.get_by_role('button', name='Get 3 outfits').click(); pg.wait_for_selector('.outfit-card', timeout=15000)
    first=pg.locator('.outfit-card').nth(0).locator('.piece-list').inner_text()
    pg.locator('.outfit-card').nth(0).get_by_role('button', name='I wore this').click(); pg.wait_for_timeout(200)
    pg.locator('.outfit-card').nth(1).get_by_role('button', name='I wore this').click(); pg.wait_for_timeout(200)
    pg.goto(URL+'#/history'); pg.wait_for_timeout(400)
    ok('history lists 2 worn outfits', pg.locator('.history-row').count()==2)
    pg.locator('.history-row').nth(1).get_by_role('radio', name='5 stars').click()
    pg.locator('.history-row').nth(1).get_by_role('button', name='Loved it').click(); pg.wait_for_timeout(300)
    pg.locator('.history-row').nth(0).get_by_role('radio', name='1 star', exact=True).click(); pg.wait_for_timeout(300)
    learned=pg.locator('.notice').first.inner_text()
    ok('learned taste summary', 'from 2 rated outfits' in learned and 'Favourites' in learned, learned[:160])
    pg.reload(); pg.wait_for_timeout(700); pg.goto(URL+'#/history'); pg.wait_for_timeout(300)
    ok('ratings persist after reload', pg.locator('.stars button.on').count()==6)
    pg.goto(URL+'#/create'); pg.wait_for_timeout(300)
    pg.get_by_role('button', name='Get 3 outfits').click(); pg.wait_for_selector('.outfit-card', timeout=15000)
    ok('create says it is personalized', pg.get_by_text('Personalized with 2 rated outfits').count()==1)
    # insights
    pg.goto(URL+'#/insights'); pg.wait_for_selector('.vtable', timeout=20000)
    rows=pg.locator('.vtable tbody tr').count()
    ok('versatility table', rows>10, f'{rows} rows, score {pg.locator(".versatility-score b").inner_text()}')
    rd=pg.locator('.outfit-card').count(); ok('rediscover suggestions', rd>0, f'{rd}')
    pg.screenshot(path='/tmp/wearwise-e2e/insights.png', full_page=True)
    pg.goto(URL+'#/history'); pg.wait_for_timeout(300); pg.screenshot(path='/tmp/wearwise-e2e/history.png', full_page=True)
    # separation: Mia history empty
    pg.locator('.profile-switch select').select_option(label='Mia'); pg.wait_for_timeout(300)
    ok('history is per person', pg.locator('.history-row').count()==0)
    ok('no page errors', not errs, '; '.join(errs[:3]))
    b.close()
print('SUMMARY', sum(res), '/', len(res))
